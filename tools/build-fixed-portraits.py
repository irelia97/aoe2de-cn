"""Generate fixed player-colour PNGs; preserve assignments across rebuilds."""
import json
import secrets
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'public'
CONFIG = ROOT / 'config/tech-tree-portrait-colors.json'
COLORS = [[0,0,255],[255,0,0],[0,255,0],[215,215,30],
          [126,242,225],[150,15,250],[99,103,112],[255,180,21]]
assignments = json.loads(CONFIG.read_text(encoding='utf-8')) if CONFIG.exists() else {}
civs = json.loads((PUBLIC/'tech-tree-data/manifest.json').read_text(encoding='utf-8'))['civilizations']
total = size = 0
for civ in civs:
    slug = civ['id']
    if slug not in assignments:
        assignments[slug] = secrets.choice([1,2,3,4,5,6,8])
    if slug == 'chinese':
        assignments[slug] = 4
    color = assignments[slug]
    assert color in [1,2,3,4,5,6,8]
    tree = json.loads((PUBLIC/f'tech-tree-data/civs/{slug}.json').read_text(encoding='utf-8'))
    icons = {Path(n['icon']).stem for n in tree['nodes']
             if n['available'] and (n.get('unique') or n['entity'] in ('Unit:2703', 'Unit:753')) and n['entity'].startswith('Unit:')}
    output = PUBLIC/f'assets/tech-tree/portraits-fixed/{slug}'
    output.mkdir(parents=True, exist_ok=True)
    for icon in sorted(icons):
        source = np.frombuffer((PUBLIC/f'assets/tech-tree/portraits-rgba/{icon}.rgba').read_bytes(), dtype=np.uint8).reshape(256,256,4)
        alpha = np.asarray(Image.open(PUBLIC/f'assets/tech-tree/portraits-png/{icon}.png').convert('RGBA'))[:,:,3]
        weight = source[:,:,3:4].astype(np.float64)/255
        shaded = source[:,:,:3]*(weight+(1-weight)*np.array(COLORS[color-1])/255)
        rgb = np.minimum(255, np.floor(shaded*255/np.maximum(alpha[:,:,None],1)+.5)).astype(np.uint8)
        rgb[alpha == 0] = 0
        result = np.dstack([rgb,alpha])
        target = output/f'{icon}.png'
        Image.fromarray(result).save(target, optimize=True)
        assert np.array_equal(np.asarray(Image.open(target))[:,:,3], alpha)
        total += 1
        size += target.stat().st_size
CONFIG.write_text(json.dumps(assignments, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
module = '// Generated by tools/build-fixed-portraits.py.\n'
module += 'export const portraitColors=Object.freeze('+json.dumps(assignments,sort_keys=True)+');\n'
module += "export const portraitAssetVersion='185872-fixed6';\n"
module += "export const portraitAssetUrl=(icon,civ)=>`${icon.replace('/Unit/',`/portraits-fixed/${civ}/`)}?v=${portraitAssetVersion}`;\n"
(PUBLIC/'tech-tree-fixed-portraits.js').write_text(module, encoding='utf-8')
print(f'Built {total} fixed transparent portraits, {size} bytes; Chinese = player 4 yellow')
